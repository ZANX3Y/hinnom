"""Check that published packages still fit the current Void Linux repositories."""

import argparse
from collections import namedtuple
from pathlib import Path
import re
import subprocess
import sys

from package_catalog import REPOSITORY_URL, ROOT, CatalogError, read_index, read_templates


VOID_URL = "https://repo-default.voidlinux.org/current"
VOID_REPOSITORIES = (VOID_URL, f"{VOID_URL}/nonfree")

# kind is "soname", "dependency" or "replaced"; only a missing soname is fixed by a rebuild.
Problem = namedtuple("Problem", "package kind detail")


def dependency_name(pattern):
    """Return the package name from an XBPS pattern: name>=1.0, name<2 or name-1.0_1."""
    name = re.match(r"[^<>=]*", pattern)[0]
    if name == pattern:
        name = re.sub(r"-[^-]+_\d+$", "", name)
    return name


def providers(index, skip=frozenset()):
    """Map sonames and package names, including virtual packages, to the package providing them."""
    sonames, names = {}, {}
    for name, package in index.items():
        if name in skip:
            continue
        names.setdefault(name, name)
        for virtual in package.get("provides", ()):
            names.setdefault(dependency_name(virtual), name)
        for soname in package.get("shlib-provides", ()):
            sonames.setdefault(soname, name)
    return sonames, names


def check_compatibility(published, void):
    """Return the problems of published packages that no longer fit Void.

    A published package that shares a name with a Void package replaces it, so
    the replaced Void package provides nothing. Void packages that still link
    against a library only the replaced package provided are reported too.
    """
    shadowed = published.keys() & void.keys()
    void_sonames, void_names = providers(void, shadowed)
    own_sonames, own_names = providers(published)
    sonames = void_sonames | own_sonames
    names = void_names | own_names

    problems = []
    for name, package in sorted(published.items()):
        for soname in package.get("shlib-requires", ()):
            if soname not in sonames:
                problems.append(Problem(name, "soname", f"links against {soname}, which no package provides"))
        for dependency in package.get("run_depends", ()):
            if dependency_name(dependency) not in names:
                problems.append(Problem(name, "dependency", f"depends on {dependency}, which no package provides"))

    dropped = {}
    for name in shadowed:
        for soname in set(void[name].get("shlib-provides", ())) - set(published[name].get("shlib-provides", ())):
            if soname not in sonames:
                dropped[soname] = name
    for name, package in sorted(void.items()):
        if name in shadowed:
            continue
        for soname in package.get("shlib-requires", ()):
            if soname in dropped:
                problems.append(Problem(dropped[soname], "replaced", f"replaces Void's {soname}, which Void's {name} still links against"))
    return problems


def bump_revisions(problems, published, templates_dir):
    """Bump the revision of each template whose published build links against a missing library.

    A template is bumped only while it matches the published build, so a rebuild
    that is pending or failed is never bumped again. Returns the bumped sources
    with their problems, and the problems a bump does not handle.
    """
    templates = read_templates(templates_dir)
    candidates = {}
    unhandled = []
    for problem in problems:
        source = published[problem.package].get("sourcepkg", problem.package)
        if problem.kind == "soname" and source in templates:
            candidates.setdefault(source, []).append(problem)
        else:
            unhandled.append(problem)

    bumped = {}
    for source, source_problems in sorted(candidates.items()):
        template = templates[source]
        built = published[source_problems[0].package]["pkgver"].removeprefix(f"{source_problems[0].package}-")
        if template["package_version"] != built:
            unhandled.extend(Problem(problem.package, problem.kind, f"{problem.detail}; template {template['package_version']} is awaiting a rebuild") for problem in source_problems)
            continue
        path = Path(templates_dir) / source / "template"
        text, count = re.subn(r"^revision=\d+$", f"revision={template['revision'] + 1}", path.read_text(), count=1, flags=re.MULTILINE)
        if count != 1:
            raise CatalogError(f"{path}: cannot find the revision to bump")
        path.write_text(text)
        bumped[source] = (f"{source}-{built}", source_problems)

    # Dependencies generated from a missing library are regenerated by the same rebuild.
    # One that survives it is reported on the next run, when nothing is bumped.
    remaining = []
    for problem in unhandled:
        source = published[problem.package].get("sourcepkg", problem.package)
        if problem.kind == "dependency" and source in bumped:
            bumped[source][1].append(problem)
        else:
            remaining.append(problem)
    return bumped, remaining


def commit_bumps(bumped, templates_dir):
    for source, (pkgver, problems) in bumped.items():
        body = f"{pkgver} needs libraries that Void no longer provides:\n\n"
        body += "\n".join(f"- {problem.package} {problem.detail}" for problem in problems)
        path = Path(templates_dir).resolve() / source / "template"
        subprocess.run(["git", "-C", str(path.parent), "commit", "-q", "-m", f"{source}: rebuild for current Void libraries", "-m", body, "--", str(path)], check=True)


def index_location(location, arch):
    return location if location.endswith("-repodata") else f"{location.rstrip('/')}/{arch}-repodata"


def main(argv=None):
    parser = argparse.ArgumentParser(description="Check published packages against the current Void Linux repositories.")
    parser.add_argument("--arch", default="x86_64")
    parser.add_argument("--repository", metavar="URL_OR_PATH", help=f"published repository; default: {REPOSITORY_URL}/ARCH")
    parser.add_argument("--void-repository", action="append", metavar="URL_OR_PATH", help="repeat for each Void repository; default: current and current/nonfree")
    parser.add_argument("--templates", type=Path, default=ROOT / "srcpkgs")
    parser.add_argument("--bump", action="store_true", help="bump the revision of templates whose builds link against missing libraries")
    parser.add_argument("--commit", action="store_true", help="with --bump, commit each bumped template")
    args = parser.parse_args(argv)
    try:
        published = read_index(index_location(args.repository or f"{REPOSITORY_URL}/{args.arch}", args.arch))
        void = {}
        for location in args.void_repository or VOID_REPOSITORIES:
            void |= read_index(index_location(location, args.arch))
    except CatalogError as exc:
        print(f"check-compat: {exc}", file=sys.stderr)
        return 2
    problems = check_compatibility(published, void)
    bumped = {}
    if args.bump or args.commit:
        try:
            bumped, problems = bump_revisions(problems, published, args.templates)
            if args.commit:
                commit_bumps(bumped, args.templates)
        except (CatalogError, OSError, subprocess.CalledProcessError) as exc:
            print(f"check-compat: {exc}", file=sys.stderr)
            return 2
    for source, (pkgver, source_problems) in bumped.items():
        for problem in source_problems:
            print(f"{problem.package}: {problem.detail}")
        print(f"{source}: bumped revision to rebuild {pkgver}")
    for problem in problems:
        print(f"{problem.package}: {problem.detail}")
    if problems:
        return 1
    if bumped:
        return 0
    print(f"{len(published)} published packages are compatible with {len(void)} Void packages")
    return 0
